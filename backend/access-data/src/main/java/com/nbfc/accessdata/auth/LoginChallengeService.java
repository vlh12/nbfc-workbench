package com.nbfc.accessdata.auth;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.util.HexFormat;
import java.util.Locale;
import java.util.Optional;
import java.util.UUID;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.security.authentication.BadCredentialsException;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

@Service
public class LoginChallengeService {

    private static final String CODE_CHARACTERS =
            "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

    private static final String ACCOUNT_SELECT = """
            SELECT id, username, password_hash, role_name, status, version
            FROM wb_app_user
            """;

    private final JdbcTemplate jdbc;
    private final PasswordEncoder passwordEncoder;
    private final TransactionTemplate transactions;
    private final SecureRandom random = new SecureRandom();
    private final String dummyPasswordHash;

    public LoginChallengeService(
            JdbcTemplate jdbc,
            PasswordEncoder passwordEncoder,
            PlatformTransactionManager transactionManager) {

        this.jdbc = jdbc;
        this.passwordEncoder = passwordEncoder;
        this.transactions = new TransactionTemplate(transactionManager);

        this.dummyPasswordHash =
                passwordEncoder.encode(UUID.randomUUID().toString());
    }

    public VerifiedLogin checkCredentials(
            String username,
            String password,
            ApplicationRole selectedRole) {

        String normalizedUsername = username == null
                ? ""
                : username.strip().toLowerCase(Locale.ROOT);

        Account account =
                normalizedUsername.matches("[a-z][a-z0-9._-]{2,63}")
                ? loadAccount(
                        ACCOUNT_SELECT + " WHERE username = ?",
                        normalizedUsername)
                : null;

        String suppliedPassword = password == null ? "" : password;

        boolean validPasswordLength =
                suppliedPassword.length() <= 72
                && suppliedPassword.getBytes(
                        StandardCharsets.UTF_8).length <= 72;

        String storedHash = account == null
                ? dummyPasswordHash
                : account.passwordHash();

        boolean passwordMatches = passwordEncoder.matches(
                validPasswordLength ? suppliedPassword : "",
                storedHash);

        if (!validPasswordLength
                || !passwordMatches
                || account == null
                || !"ACTIVE".equals(account.status())
                || selectedRole == null
                || !account.role().equals(selectedRole.name())) {

            throw new BadCredentialsException(
                    "Invalid username, password, or selected role.");
        }

        return new VerifiedLogin(
                account.id(),
                account.username(),
                account.role(),
                account.version());
    }

    /*
     * browserBinding must be generated by the backend controller
     * and retained in the pending browser session.
     * Never trust a binding supplied by the login form.
     */
    public IssuedCode begin(
            String username,
            String password,
            ApplicationRole selectedRole,
            String browserBinding) {

        if (!validBinding(browserBinding)) {
            throw new IllegalArgumentException(
                    "A server-generated browser binding is required.");
        }

        VerifiedLogin account = checkCredentials(
                username,
                password,
                selectedRole);

        String challengeId = UUID.randomUUID().toString();
        String displayedCode = generateCode();

        jdbc.update("""
                INSERT INTO wb_login_challenge (
                    id,
                    user_id,
                    binding_hash,
                    code_hash,
                    account_version,
                    role_name,
                    attempts_remaining,
                    created_at,
                    expires_at
                )
                VALUES (
                    ?, ?, ?, ?, ?, ?, 5,
                    SYSTIMESTAMP,
                    SYSTIMESTAMP + INTERVAL '5' MINUTE
                )
                """,
                challengeId,
                account.userId(),
                hash(browserBinding),
                hash(displayedCode),
                account.accountVersion(),
                account.role());

        return new IssuedCode(challengeId, displayedCode, 300);
    }

    public Optional<VerifiedLogin> verify(
            String challengeId,
            String enteredCode,
            String browserBinding) {

        if (challengeId == null || !validBinding(browserBinding)) {
            return Optional.empty();
        }

        String normalizedCode =
                enteredCode != null && enteredCode.length() <= 12
                ? enteredCode.strip().toUpperCase(Locale.ROOT)
                : "";

        return transactions.execute(transaction -> {

            Challenge challenge = jdbc.query("""
                    SELECT user_id,
                           binding_hash,
                           code_hash,
                           account_version,
                           role_name,
                           attempts_remaining,
                           CASE
                               WHEN used_at IS NULL
                                AND expires_at > SYSTIMESTAMP
                               THEN 1
                               ELSE 0
                           END AS usable
                    FROM wb_login_challenge
                    WHERE id = ?
                    FOR UPDATE
                    """,
                    (rs, rowNumber) -> new Challenge(
                            rs.getString("user_id"),
                            rs.getString("binding_hash"),
                            rs.getString("code_hash"),
                            rs.getLong("account_version"),
                            rs.getString("role_name"),
                            rs.getInt("attempts_remaining"),
                            rs.getInt("usable") == 1),
                    challengeId)
                    .stream()
                    .findFirst()
                    .orElse(null);

            if (challenge == null
                    || !challenge.usable()
                    || challenge.attemptsRemaining() <= 0
                    || !sameHash(
                            challenge.bindingHash(),
                            hash(browserBinding))) {

                return Optional.empty();
            }

            if (!sameHash(challenge.codeHash(), hash(normalizedCode))) {

                jdbc.update("""
                        UPDATE wb_login_challenge
                        SET attempts_remaining = attempts_remaining - 1
                        WHERE id = ?
                          AND used_at IS NULL
                          AND attempts_remaining > 0
                          AND expires_at > SYSTIMESTAMP
                        """,
                        challengeId);

                // Return normally so the failed attempt is committed.
                return Optional.empty();
            }

            int consumed = jdbc.update("""
                    UPDATE wb_login_challenge
                    SET used_at = SYSTIMESTAMP
                    WHERE id = ?
                      AND used_at IS NULL
                      AND attempts_remaining > 0
                      AND expires_at > SYSTIMESTAMP
                    """,
                    challengeId);

            if (consumed != 1) {
                return Optional.empty();
            }

            Account currentAccount = loadAccount(
                    ACCOUNT_SELECT + " WHERE id = ?",
                    challenge.userId());

            if (currentAccount == null
                    || !"ACTIVE".equals(currentAccount.status())
                    || currentAccount.version()
                        != challenge.accountVersion()
                    || !currentAccount.role().equals(challenge.role())) {

                return Optional.empty();
            }

            return Optional.of(new VerifiedLogin(
                    currentAccount.id(),
                    currentAccount.username(),
                    currentAccount.role(),
                    currentAccount.version()));
        });
    }

    @Scheduled(initialDelay = 60000, fixedDelay = 60000)
    public void removeExpiredChallenges() {
        jdbc.update("""
                DELETE FROM wb_login_challenge
                WHERE expires_at <= SYSTIMESTAMP
                """);
    }

    private Account loadAccount(String query, String value) {
        return jdbc.query(
                query,
                (rs, rowNumber) -> new Account(
                        rs.getString("id"),
                        rs.getString("username"),
                        rs.getString("password_hash"),
                        rs.getString("role_name"),
                        rs.getString("status"),
                        rs.getLong("version")),
                value)
                .stream()
                .findFirst()
                .orElse(null);
    }

    private String generateCode() {
        StringBuilder code = new StringBuilder(6);

        for (int i = 0; i < 6; i++) {
            code.append(CODE_CHARACTERS.charAt(
                    random.nextInt(CODE_CHARACTERS.length())));
        }

        return code.toString();
    }

    private static boolean validBinding(String value) {
        return value != null
                && value.length() >= 32
                && value.length() <= 128;
    }

    private static String hash(String value) {
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256")
                    .digest(value.getBytes(StandardCharsets.UTF_8));

            return HexFormat.of().formatHex(digest);
        } catch (NoSuchAlgorithmException exception) {
            throw new IllegalStateException(
                    "SHA-256 is unavailable.", exception);
        }
    }

    private static boolean sameHash(String expected, String actual) {
        return MessageDigest.isEqual(
                expected.getBytes(StandardCharsets.US_ASCII),
                actual.getBytes(StandardCharsets.US_ASCII));
    }

    public record IssuedCode(
            String challengeId,
            String displayedCode,
            int expiresInSeconds) {
    }

    public record VerifiedLogin(
            String userId,
            String username,
            String role,
            long accountVersion) {
    }

    private record Account(
            String id,
            String username,
            String passwordHash,
            String role,
            String status,
            long version) {
    }

    private record Challenge(
            String userId,
            String bindingHash,
            String codeHash,
            long accountVersion,
            String role,
            int attemptsRemaining,
            boolean usable) {
    }
}